// Собирает «Инструкция.docx» (одна страница A4). Запуск: node make-instruction.js <куда сохранить>
const fs = require('fs');
const { Document, Packer, Paragraph, TextRun, AlignmentType, LevelFormat } = require('docx');

const FONT = 'Calibri';
const out = process.argv[2] || 'Инструкция.docx';

// Текст в «ёлочках» вида **так** выделяется полужирным
function runs(text) {
  return text.split('**').map((part, i) => new TextRun({ text: part, bold: i % 2 === 1, font: FONT, size: 22 }));
}
const p = (text, opts = {}) => new Paragraph({ children: runs(text), spacing: { before: 0, after: 50 }, ...opts });
const h = (text) => new Paragraph({
  children: [new TextRun({ text, bold: true, font: FONT, size: 24, color: '1F4E79' })],
  spacing: { before: 110, after: 40 }, keepNext: true,
});
let listNo = 0;
const steps = (items) => {
  const ref = 'steps' + (++listNo);
  numbering.push({ reference: ref, levels: [{ level: 0, format: LevelFormat.DECIMAL, text: '%1.', alignment: AlignmentType.LEFT,
    style: { paragraph: { indent: { left: 340, hanging: 340 } }, run: { font: FONT, size: 22 } } }] });
  return items.map((t) => new Paragraph({ children: runs(t), numbering: { reference: ref, level: 0 }, spacing: { before: 0, after: 30 } }));
};
const bullets = (items) => items.map((t) => new Paragraph({ children: runs(t), numbering: { reference: 'dots', level: 0 }, spacing: { before: 0, after: 30 } }));
const numbering = [{ reference: 'dots', levels: [{ level: 0, format: LevelFormat.BULLET, text: '•', alignment: AlignmentType.LEFT,
  style: { paragraph: { indent: { left: 340, hanging: 240 } }, run: { font: FONT, size: 22 } } }] }];

const body = [
  new Paragraph({ children: [new TextRun({ text: 'Разбор рабочего стола: как запустить, проверить план и отменить', bold: true, font: FONT, size: 30 })], spacing: { before: 0, after: 60 } }),
  p('Программа раскладывает файлы рабочего стола по папкам, даёт им понятные имена и собирает «Каталог рабочего стола.html». Она ничего не удаляет, а любой разбор можно отменить.'),

  h('1. Установка (один раз)'),
  ...steps([
    'Щёлкните скачанный архив правой кнопкой, выберите «Свойства», поставьте галочку **«Разблокировать»** (если она есть) и нажмите «ОК».',
    'Создайте на рабочем столе папку **_Каталог** и распакуйте в неё все файлы архива.',
    'Откройте «Настройки.txt», найдите раздел **[Суда КМТФ]** и впишите суда, по одному в строке: название, знак | и номер ИМО. Пример: Астана, Astana | 9123456. Сохраните файл. Без этого списка программа не начнёт работу.',
  ]),

  h('2. Проба на копиях (перед первым настоящим разбором)'),
  ...steps([
    'Создайте в «Документах» папку, например «Проба», и **скопируйте** в неё 10–15 разных файлов.',
    'В «Настройки.txt» в строке **ТестоваяПапка =** укажите путь к этой папке (скопируйте его из адресной строки Проводника). Сохраните файл.',
    'Запустите **Start.bat** двойным щелчком. При первом запуске программа попросит ключ доступа к Claude: вставьте его и нажмите Enter. Если Windows спросит о запуске скрипта, введите R и нажмите Enter.',
    'Введите **1** («Только план») и нажмите Enter. В этом режиме ни один файл не меняется.',
  ]),

  h('3. Проверка плана'),
  p('Откроется страница «План разбора.html»: по каждому файлу видно, в какую папку он пойдёт и как будет назван. Жёлтым выделены файлы, которые программа не смогла уверенно отнести к папке, они пойдут в «На разбор».'),
  p('Чтобы исправить план, откройте файл **План разбора.xlsx** (путь к нему программа показывает в своём окне). В столбцах «Папка назначения» и «Новое имя» можно вписать своё. Папку берите из листа «Папки». Если очистить «Папку назначения», файл останется на месте. Сохраните файл и закройте Excel.'),

  h('4. Разбор'),
  p('Запустите Start.bat и введите **2** («Применить исправленный план»). Программа спросит, применять ли план. Напечатайте слово **да** и нажмите Enter: только после этого файлы перемещаются. Любой другой ответ ничего не меняет. В конце программа покажет отчёт и создаст каталог.'),

  h('5. Откат'),
  p('Запустите Start.bat, введите **5** и ответьте **да**. Последний разбор отменяется: файлы возвращаются на прежние места с прежними именами. Чтобы отменить и предыдущий разбор, запустите откат ещё раз.'),

  h('6. Настоящий рабочий стол'),
  p('Когда проба вас устроила, сотрите путь в строке «ТестоваяПапка =» (после знака = должно быть пусто), сохраните файл и повторите шаги: **1** (план), проверка плана, **2** (разбор). Первый разбор всего рабочего стола займёт несколько часов, окно можно свернуть. Если работу прервать, при следующем запуске программа продолжит с того же места.'),

  h('7. Что полезно знать'),
  ...bullets([
    'Документы с пометкой «Для служебного пользования» программа не отправляет в Claude, не перемещает и не переименовывает. Файлы с паролем она кладёт в папку «Файлы ДСП».',
    'Каталог открывается двойным щелчком по файлу «Каталог рабочего стола.html». Чтобы цветные метки не пропали, нажимайте в каталоге кнопку «Сохранить метки в файл» (файл labels.json в папке «_Каталог»).',
    'Остальные пункты меню: **3** делает план и разбор за один запуск (без правки плана), **4** только обновляет каталог.',
    'Если что-то пошло не так, ничего не исправляйте вручную, а пришлите файл **Ход работы.log** из папки «_Каталог».',
  ]),
];

const doc = new Document({
  creator: 'Desktop sorter', title: 'Разбор рабочего стола: инструкция',
  styles: { default: { document: { run: { font: FONT, size: 22 } } } },
  numbering: { config: numbering },
  sections: [{ properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 1000, bottom: 900, left: 1134, right: 1080 } } }, children: body }],
});
Packer.toBuffer(doc).then((buf) => { fs.writeFileSync(out, buf); console.log('written', out, buf.length, 'bytes'); });
