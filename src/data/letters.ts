/** Сыфаты буквы выводятся из единого источника — списков sifat.letters */
export function getSifatIdsForLetter(letterId: LetterId): SifatId[] {
  return sifatList.filter((s) => s.letters.includes(letterId)).map((s) => s.id);
}

export const lettersWithSifat: LetterWithSifat[] = letters.map((l) => ({
  ...l,
  sifatIds: getSifatIdsForLetter(l.id),
}));

export const letterWithSifatById: Record<LetterId, LetterWithSifat> = Object.fromEntries(
  lettersWithSifat.map((l) => [l.id, l]),
) as Record<LetterId, LetterWithSifat>;

